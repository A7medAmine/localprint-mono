// Emit the credentials file that ships inside the packaged app.
//
// Why this exists: electron/main.js loads a .env from the asar at startup so
// the Gmail OAuth client has GOOGLE_CLIENT_ID / GOOGLE_CLIENT_SECRET. The
// repo's own .env is gitignored and is never present on the release runner,
// so without this step the packaged app starts with both vars undefined and
// "Connect Gmail" fails with "Google OAuth credentials not configured".
//
// Only the two Google values are written. The repo .env also holds
// TOKEN_ENCRYPTION_KEY, which must NOT be shipped — main.js generates a
// per-install key under userData when it is unset, and baking one key into
// the installer would give every installation the same key.
//
// Values come from the environment first (GitHub Actions secrets), then from
// apps/desktop/.env so a local `npm run electron:build` keeps working.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const desktopDir = path.resolve(__dirname, '..');
const localEnvPath = path.join(desktopDir, '.env');
const outPath = path.join(desktopDir, '.env.packaged');

const KEYS = ['GOOGLE_CLIENT_ID', 'GOOGLE_CLIENT_SECRET'];

// Minimal KEY=VALUE reader. Deliberately not dotenv: this script runs before
// the app's own dependency graph matters, and the format we write is our own.
function readLocalEnv() {
  if (!fs.existsSync(localEnvPath)) return {};
  const out = {};
  for (const line of fs.readFileSync(localEnvPath, 'utf8').split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const eq = trimmed.indexOf('=');
    if (eq === -1) continue;
    const key = trimmed.slice(0, eq).trim();
    let value = trimmed.slice(eq + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    out[key] = value;
  }
  return out;
}

const local = readLocalEnv();
const resolved = {};
const missing = [];

for (const key of KEYS) {
  const value = process.env[key] || local[key];
  // .env.example ships literal placeholders; treat those as missing so a
  // half-configured checkout fails here instead of at runtime in the installer.
  if (!value || value.startsWith('your_')) {
    missing.push(key);
    continue;
  }
  resolved[key] = value;
}

if (missing.length) {
  console.error('\ngenerate-packaged-env: cannot build a working installer.\n');
  console.error(`Missing: ${missing.join(', ')}\n`);
  console.error('Set them as repository secrets (CI) or in apps/desktop/.env (local),');
  console.error('then run the build again. Values come from the Google Cloud Console');
  console.error('OAuth client for Atba3li.\n');
  process.exit(1);
}

const body =
  '# GENERATED by scripts/generate-packaged-env.js — do not edit, do not commit.\n' +
  '# Shipped inside the packaged app and loaded by electron/main.js.\n' +
  KEYS.map((key) => `${key}=${resolved[key]}`).join('\n') +
  '\n';

fs.writeFileSync(outPath, body, { mode: 0o600 });
console.log(`generate-packaged-env: wrote ${outPath} (${KEYS.join(', ')})`);
